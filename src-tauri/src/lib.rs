//! Tauri app crate: thin commands that call into `dbrief-core`.

mod commands;

use std::sync::Mutex;

use dbrief_core::{SettingsFile, Storage};
use tauri::Manager;

pub struct AppState {
    pub storage: Storage,
    pub settings: Mutex<SettingsFile>,
}

/// Builds the tauri-specta command set. Also used by the `export_bindings` test.
pub fn specta_builder() -> tauri_specta::Builder<tauri::Wry> {
    tauri_specta::Builder::<tauri::Wry>::new().commands(tauri_specta::collect_commands![
        commands::get_settings,
        commands::update_settings,
        commands::get_ui_state,
        commands::set_ui_state,
        commands::default_scripts_folder,
        commands::create_scripts_folder,
    ])
}

/// Where the generated TypeScript bindings are written (relative to this crate).
pub const BINDINGS_PATH: &str = "../src/lib/bindings.ts";

pub fn export_bindings(builder: &tauri_specta::Builder<tauri::Wry>) {
    builder
        .export(
            specta_typescript::Typescript::default()
                .header("// @ts-nocheck\n// Generated by tauri-specta. Do not edit.\n"),
            BINDINGS_PATH,
        )
        .expect("failed to export TypeScript bindings");
}

#[cfg_attr(mobile, tauri::mobile_entry_point)]
pub fn run() {
    let builder = specta_builder();

    #[cfg(debug_assertions)]
    export_bindings(&builder);

    tauri::Builder::default()
        .plugin(tauri_plugin_dialog::init())
        .plugin(tauri_plugin_os::init())
        .invoke_handler(builder.invoke_handler())
        .setup(move |app| {
            builder.mount_events(app);
            let data_dir = app.path().app_data_dir()?;
            let storage = tauri::async_runtime::block_on(Storage::open(&data_dir))?;
            let settings = SettingsFile::load(&data_dir)?;
            app.manage(AppState {
                storage,
                settings: Mutex::new(settings),
            });
            Ok(())
        })
        .run(tauri::generate_context!())
        .expect("error while running dbrief");
}

#[cfg(test)]
mod tests {
    /// `cargo test` regenerates the TypeScript bindings so they never drift from the commands.
    #[test]
    fn export_bindings() {
        super::export_bindings(&super::specta_builder());
    }
}
